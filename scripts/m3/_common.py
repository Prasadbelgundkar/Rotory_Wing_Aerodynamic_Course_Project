"""
Shared helpers for the Milestone 3 report scripts (scripts/m3/*).

Same conventions as scripts/m2/_common.py:
* puts src/ on the path and uses the frozen aircraft of src/m2/aircraft_input_m2.py,
* `save_figure()` saves to outputs/m3/ and records a caption (flight condition
  + assumptions) in outputs/m3/captions.json / FIGURES.md (figure index),
* `write_text()` writes markdown / CSV tables to outputs/m3/.
The design mission is read from inputs/m3_design_mission.json.
"""
import json
import os
import sys

for _var in ("OPENBLAS_NUM_THREADS", "OMP_NUM_THREADS", "MKL_NUM_THREADS"):
    os.environ.setdefault(_var, "1")

import numpy as np                                  # noqa: E402,F401

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
SRC = os.path.join(ROOT, 'src')
if SRC not in sys.path:
    sys.path.insert(0, SRC)

import matplotlib                                   # noqa: E402
matplotlib.use(os.environ.get("MPLBACKEND", "Agg"))
import matplotlib.pyplot as plt                     # noqa: E402

import m2.aircraft_input_m2 as CFG                  # noqa: E402

DEFAULT_MISSION = os.path.join(ROOT, 'inputs', 'm3_design_mission.json')
OUT_DIR = os.path.join(ROOT, 'outputs', 'm3')
M2_DIR = os.path.join(ROOT, 'outputs', 'm2', f'rotor_{CFG.ROTOR_VARIANT}')
os.makedirs(OUT_DIR, exist_ok=True)
_CAPTIONS = os.path.join(OUT_DIR, 'captions.json')

plt.rcParams.update({
    "figure.dpi": 110, "savefig.dpi": 200, "font.size": 10,
    "axes.grid": True, "grid.linestyle": ":", "grid.alpha": 0.6,
    "axes.titlesize": 11, "legend.fontsize": 8.5,
})

MODEL_NOTE = (f"final design: rotor '{CFG.ROTOR_VARIANT}' (twist {CFG.TWIST_DESC}), 2 x {CFG.ENGINE_NAME}; "
              "6-DOF trim with rigid-disk azimuth-resolved BEMT (annular-Glauert inflow + K-factor, linear airfoil, "
              "stall 14 deg), no rotor-wake/wing interference or hover download")


def save_figure(fig, name: str, section: str, caption: str):
    path = os.path.join(OUT_DIR, f"{name}.png")
    fig.savefig(path, bbox_inches='tight')
    plt.close(fig)
    caps = {}
    if os.path.exists(_CAPTIONS):
        with open(_CAPTIONS, encoding='utf-8') as f:
            caps = json.load(f)
    caps[name] = {"section": section, "caption": caption}
    with open(_CAPTIONS, 'w', encoding='utf-8') as f:
        json.dump(caps, f, indent=1)
    _write_index(caps)
    print(f"  saved {os.path.relpath(path, ROOT)}")
    return path


def _sec_key(item):
    sec = item[1]["section"]
    return [int(p) if p.isdigit() else p for p in sec.replace('.', ' ').split()], item[0]


def _write_index(caps):
    lines = ["# Milestone 3 figure index", "",
             "Generated by scripts/m3/* (run `python run_all_m3.py`). Each caption states the flight condition and "
             "assumptions.", "", "| Section | Figure | Caption |", "|---|---|---|"]
    for name, c in sorted(caps.items(), key=_sec_key):
        lines.append(f"| {c['section']} | `{name}.png` | {c['caption']} |")
    with open(os.path.join(OUT_DIR, 'FIGURES.md'), 'w', encoding='utf-8') as f:
        f.write("\n".join(lines) + "\n")


def write_text(name: str, text: str):
    path = os.path.join(OUT_DIR, name)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(text)
    print(f"  saved {os.path.relpath(path, ROOT)}")
    return path


def md_table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)
